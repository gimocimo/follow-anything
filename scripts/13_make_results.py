#!/usr/bin/env python3
"""Generate `results/rung3_baseline.json` FROM the runtime manifests (Rung 3).

The committed result must be *derived*, not hand-curated: an auditor should be able to re-run
this against the same artifacts and get the same file. It also re-derives the leak-free chain
as booleans, so a broken link shows up in the committed result instead of in prose.

Inputs:
  <dev-dir>/baseline_metrics.json     (scripts/06, dev = game 4)
  <dev-dir>/perclass_metrics.json     (scripts/11)
  <dev-dir>/occlusion_metrics.json    (scripts/12)
  <final-dir>/baseline_metrics.json   (scripts/06, sealed final = game 2)
  <prov-dir>/export_manifest.json     (scripts/09)
  <prov-dir>/train_manifest.json      (scripts/10)

    python scripts/13_make_results.py
"""
import argparse
import json
from pathlib import Path

PROJ = Path(__file__).resolve().parents[1]
DEV_BASELINE = 0.4814830134807477      # results/rung1_baseline.json  dev.metrics.HOTA
FINAL_BASELINE = 0.49209979323992903   # results/rung1_baseline.json  final.metrics.HOTA


def _load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def build(dev, fin, pc, oc, em, tm):
    de = tm.get("dataset_export") or {}
    pre = tm.get("dataset_verified_pre") or {}
    post = tm.get("dataset_verified_post") or {}
    wsha = dev["provenance"]["detector"]["sha256"]
    return {
        "note": "Rung-3 result: fine-tuned yolo11m + tuned tracker, scored with the SAME sealed eval "
                "as Rung 1. GENERATED by scripts/13_make_results.py from the runtime manifests. "
                "dev = train game 4; final = valid game 2 (sealed, one-shot). Proof manifests in "
                "results/rung3_provenance/.",
        "leak_free": {
            "detector_training": "yolo11m fine-tuned on GSR train games {6,9} ONLY (leave-one-game-out); "
                                 "disjoint from both eval games (4 dev, 2 final)",
            "export_games": em.get("observed_games"),
            "export_sha256": em.get("export_sha256"),
            "train_manifest_links_export": de.get("export_sha256") == em.get("export_sha256"),
            "dataset_verified_before_training": bool(pre.get("ok")),
            "dataset_verified_after_training": bool(post.get("ok")),
            "provably_leave_one_game_out": bool(tm.get("provably_leave_one_game_out")),
            "weights_sha256": wsha,
            "train_manifest_binds_output_checkpoint": tm.get("output_best_sha256") == wsha,
            "dev_and_final_same_checkpoint": fin["provenance"]["detector"]["sha256"] == wsha,
        },
        "tracker": {"config": dev["provenance"]["tracker"].get("resolved"),
                    "sha256": dev["provenance"]["tracker"].get("sha256")},
        "dev": {"eval_game": "4", "n_seqs": dev.get("n_seqs"), "metrics": dev["metrics"],
                "baseline_HOTA": DEV_BASELINE, "delta_HOTA": dev["metrics"]["HOTA"] - DEV_BASELINE,
                "git_sha": dev["provenance"].get("git_sha")},
        "final": {"eval_game": "2", "n_seqs": fin.get("n_seqs"), "metrics": fin["metrics"],
                  "baseline_HOTA": FINAL_BASELINE, "delta_HOTA": fin["metrics"]["HOTA"] - FINAL_BASELINE,
                  "gate": f"beat {FINAL_BASELINE} -> " + ("MET" if fin["metrics"]["HOTA"] > FINAL_BASELINE else "NOT MET"),
                  "git_sha": fin["provenance"].get("git_sha")},
        "per_class_dev": (pc or {}).get("per_class"),
        "occlusion_dev": oc,
        "packages": dev["provenance"].get("packages"),
        "device": dev["provenance"].get("device"),
        "python": dev["provenance"].get("python"),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dev-dir", default="outputs/gsr_ft_dev")
    ap.add_argument("--final-dir", default="outputs/gsr_ft_final")
    ap.add_argument("--prov-dir", default="results/rung3_provenance")
    ap.add_argument("--out", default="results/rung3_baseline.json")
    args = ap.parse_args()

    dev = _load(Path(args.dev_dir) / "baseline_metrics.json")
    fin = _load(Path(args.final_dir) / "baseline_metrics.json")
    pc = _load(Path(args.dev_dir) / "perclass_metrics.json")
    oc = _load(Path(args.dev_dir) / "occlusion_metrics.json")
    em = _load(Path(args.prov_dir) / "export_manifest.json")
    tm = _load(Path(args.prov_dir) / "train_manifest.json")
    missing = [n for n, v in (("dev metrics", dev), ("final metrics", fin),
                              ("export_manifest", em), ("train_manifest", tm)) if v is None]
    if missing:
        raise SystemExit(f"missing required inputs: {missing}")

    out = build(dev, fin, pc, oc, em, tm)
    Path(args.out).write_text(json.dumps(out, indent=2) + "\n")
    lf = out["leak_free"]
    print(f"wrote {args.out}")
    print(f"  dev   HOTA {out['dev']['metrics']['HOTA']:.4f}  ({out['dev']['delta_HOTA']:+.4f})")
    print(f"  final HOTA {out['final']['metrics']['HOTA']:.4f}  ({out['final']['delta_HOTA']:+.4f})  -> {out['final']['gate']}")
    print(f"  leak-free chain: export{lf['export_games']} linked={lf['train_manifest_links_export']} "
          f"verified_pre={lf['dataset_verified_before_training']} verified_post={lf['dataset_verified_after_training']} "
          f"binds_ckpt={lf['train_manifest_binds_output_checkpoint']} "
          f"same_ckpt_dev_final={lf['dev_and_final_same_checkpoint']}")
    if not lf["provably_leave_one_game_out"]:
        print("  NOTE: provably_leave_one_game_out = False (checkpoint predates train-time verification)")


if __name__ == "__main__":
    main()
